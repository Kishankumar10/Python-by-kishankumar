# arithmetic ( +, -, , /, //, %, *)
print(10 + 10)
print(34 - 2)
print(2 * 5)
print(10/2)
print(10 % 2)
print(10 // 2)
print(2 ** 4)

# assignment ( =, +=, -=, *=, /=, %=)
a = 100
a += 5      # a = a + 5
print(a)
a -= 10    # a = a - 10
print(a)

# comparison ( ==, !=, >, <, >=, <=)
# comparison operator always returns the boolean ( True, False ) values

x = 4
y = 5
print(100 == 100)
print( x == y)

print(x != y)

print( x > y)
print(x < y)

print( x >= y)
print(x >= 4)
print(y <= 7)

