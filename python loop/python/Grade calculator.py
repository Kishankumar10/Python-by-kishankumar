##Grade calculator

a=int(input("what is your percentage in your exam :"))

if 90 <= a <= 100 :
    print("you secured 'A' grade")
elif 80 <= a < 90 :
    print("you secured 'B' grade")
elif 70 <= a < 80 :
    print("you secured 'C' grade")
elif 60 <= a < 70 :
    print("you secured 'D' grade")
else :
    print("you secured 'E' grade")
