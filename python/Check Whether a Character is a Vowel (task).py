##Check Whether a Character is a Vowel

character=input("enter your character:")

if character=="a" or character=="e" or character=="i" or character=="o" or character=="u":
    print("your character is a vowel in lowercase")
elif character=="A" or character=="E" or character=="I" or character=="O" or character=="U":
    print("your character is a vowel in uppercase")
else :
    print("your character is not a vowel")
